export function embeddingInputForDocument(document: SearchDocument): EmbeddingInput {
  const safeText = normalizeSearchText(redactSensitiveText(`${document.title}\n${document.normalizedText}`));
  return {
    id: document.id,
    text: safeText,
    contentHash: contentHash(safeText),
  };
}

export function documentsNeedingEmbedding(documents: SearchDocument[], embeddings: SearchEmbedding[], provider: VectorSearchProvider) {
  const current = new Map(
    embeddings
      .filter((embedding) => embedding.provider === provider.provider && embedding.model === provider.model)
      .map((embedding) => [embedding.searchDocumentId, embedding]),
  );
  return documents.filter((document) => {
    const input = embeddingInputForDocument(document);
    return current.get(document.id)?.contentHash !== input.contentHash;
  });
}

export function containsEmbeddingSecret(text: string) {
  return /\[redacted-secret\]|\bsk-[A-Za-z0-9_-]{8,}|(?:api[_-]?key|secret|token|password)\s*[:=]/i.test(redactSensitiveText(text));
}

function hashVector(text: string, dimensions: number) {
  const values = Array.from({ length: dimensions }, () => 0);
  const words = normalizeSearchText(text).split(" ").filter(Boolean);
  words.forEach((word, index) => {
    const hash = Number.parseInt(contentHash(`${word}:${index}`).replace("fnv1a-", ""), 16);
    values[hash % dimensions] += ((hash % 2000) / 1000 - 1) || 0.1;
  });
  const magnitude = Math.sqrt(values.reduce((sum, value) => sum + value * value, 0)) || 1;
  return values.map((value) => value / magnitude);
}

function cosine(left: number[], right: number[]) {
  return left.reduce((sum, value, index) => sum + value * (right[index] ?? 0), 0);
}
