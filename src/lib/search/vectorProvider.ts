import type { SearchDocument, SearchEmbedding } from "../../types/domain";
import { contentHash, normalizeSearchText, redactSensitiveText } from "./text";

export interface EmbeddingInput {
  id: string;
  text: string;
  contentHash: string;
}

export interface VectorSearchProvider {
  readonly provider: string;
  readonly model: string;
  readonly dimensions: number;
  embed(inputs: EmbeddingInput[]): Promise<Array<{ id: string; vector: number[] }>>;
  search(_query: string, _documents: SearchDocument[], _embeddings: SearchEmbedding[]): Promise<Array<{ searchDocumentId: string; score: number }>>;
}

export class NoVectorProvider implements VectorSearchProvider {
  readonly provider = "none";
  readonly model = "disabled";
  readonly dimensions = 0;

  async embed() {
    return [];
  }

  async search() {
    return [];
  }
}

export class MockVectorProvider implements VectorSearchProvider {
  readonly provider = "mock";
  readonly model = "mock-hash-16";
  readonly dimensions = 16;

  async embed(inputs: EmbeddingInput[]) {
    return inputs.map((input) => ({ id: input.id, vector: hashVector(input.text, this.dimensions) }));
  }

  async search(query: string, documents: SearchDocument[]) {
    const queryVector = hashVector(query, this.dimensions);
    return documents
      .map((document) => ({
        searchDocumentId: document.id,
        score: cosine(queryVector, hashVector(document.normalizedText, this.dimensions)),
      }))
      .filter((result) => result.score > 0)
      .sort((left, right) => right.score - left.score);
  }
}

